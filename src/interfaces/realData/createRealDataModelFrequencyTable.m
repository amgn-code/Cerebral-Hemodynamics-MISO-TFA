function frequencyTable = createRealDataModelFrequencyTable(results)
% createRealDataModelFrequencyTable Create the table for one model page.
%
% Phase is reported in degrees to keep the table readable for users who
% work with physiological transfer-function results.

    modelName = validateModelResults(results);

    if modelName == "MISO"
        model = results.misoResults;
        frequencyTable = table( ...
            column(model.f), ...
            column(model.map.gain), ...
            column(rad2deg(model.map.phase.wrapped)), ...
            column(model.map.coherence.partial), ...
            column(model.co2.gain), ...
            column(rad2deg(model.co2.phase.wrapped)), ...
            column(model.co2.coherence.partial), ...
            column(model.system.multipleCoherence), ...
            column(model.inputRelationship.coherence), ...
            column(rad2deg(model.inputRelationship.phase.wrapped)), ...
            VariableNames=[ ...
                "FrequencyHz", ...
                "MAPGain", "MAPPhaseDegrees", ...
                "MAPPartialCoherence", ...
                "CO2Gain", "CO2PhaseDegrees", ...
                "CO2PartialCoherence", ...
                "MultipleCoherence", ...
                "MAPCO2Coherence", "MAPCO2PhaseDegrees"]);
    else
        model = results.sisoResults;
        frequencyTable = table( ...
            column(model.f), ...
            column(model.map.gain), ...
            column(rad2deg(model.map.phase.wrapped)), ...
            column(model.map.coherence.pairwise), ...
            column(model.co2.gain), ...
            column(rad2deg(model.co2.phase.wrapped)), ...
            column(model.co2.coherence.pairwise), ...
            VariableNames=[ ...
                "FrequencyHz", ...
                "MAPGain", "MAPPhaseDegrees", "MAPCoherence", ...
                "CO2Gain", "CO2PhaseDegrees", "CO2Coherence"]);
    end

end

function modelName = validateModelResults(results)
% validateModelResults Identify one successful public model result.

    if ~isstruct(results) || ~isfield(results, "interfaceModel")
        error( ...
            "TFA:InvalidRealDataModelResults", ...
            "Provide results from runMisoRealData or runSisoRealData.");
    end

    modelName = upper(string(results.interfaceModel));
    if ~isscalar(modelName) || ~any(modelName == ["MISO", "SISO"])
        error( ...
            "TFA:UnknownRealDataModel", ...
            "interfaceModel must be MISO or SISO.");
    end

    expectedField = lower(modelName) + "Results";
    if ~isfield(results, expectedField) || isempty(results.(expectedField))
        error( ...
            "TFA:IncompleteRealDataModelResults", ...
            "%s results are empty. Check results.runStatus.", modelName);
    end

end

function values = column(values)
% column Use one row per retained frequency.

    values = values(:);

end
