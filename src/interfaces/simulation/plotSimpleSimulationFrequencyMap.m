function [figureHandle, sourceData] = plotSimpleSimulationFrequencyMap( ...
    simulationResults, dataRows, factorName, factorLabel, ...
    groupingMode, pathway, colorLimit, outputSettings)
% plotSimpleSimulationFrequencyMap Draw one primary accuracy heatmap.
%
% Frequency is the horizontal axis, the selected assigned factor is the
% vertical axis, and color is the MISO advantage in known-truth recovery.
% The score is the log10 ratio of mean SISO and MISO errors.

    if nargin < 5 || isempty(groupingMode)
        groupingMode = "exact";
    end
    if nargin < 6 || isempty(pathway)
        pathway = "map";
    end
    if nargin < 7 || isempty(colorLimit)
        colorLimit = 1.5;
    end
    if nargin < 8 || isempty(outputSettings)
        outputSettings = defaultSimulationOutputSettings("off");
    else
        outputSettings = completeSimulationOutputSettings(outputSettings);
    end

    pathway = lower(string(pathway));
    if ~ismember(pathway, ["map" "co2"])
        error( ...
            "TFA:UnknownSimulationPathway", ...
            "pathway must be map or co2.");
    end

    observations = simulationResults.observations(dataRows, :);
    observationColumns = observations.ObservationID;
    factorValues = observations.(factorName);
    frequency = simulationResults.frequency;
    groupingSettings = simulationResults.settings.grouping;
    minimumValidN = groupingSettings.minimumValidN;
    bootstrapSettings = outputSettings.bootstrap;

    pathwayResults = frequency.(pathway);
    sisoErrors = pathwayResults.sisoComplexError(:, observationColumns);
    misoErrors = pathwayResults.misoComplexError(:, observationColumns);
    summary = summarizeSimulationFrequencyAdvantage( ...
        factorValues, sisoErrors, misoErrors, factorName, ...
        groupingMode, groupingSettings, bootstrapSettings);

    [plotCenters, tickValues, tickLabels] = ...
        prepareSimulationHeatmapAxis(summary.factorLabels);
    plotValues = summary.advantage;
    plotValues(plotValues > colorLimit) = colorLimit;
    plotValues(plotValues < -colorLimit) = -colorLimit;
    displayMask = summary.validN >= minimumValidN & ...
        (isfinite(summary.advantage) | isinf(summary.advantage));

    figureHandle = figure( ...
        "Color", "white", ...
        "Visible", outputSettings.visible, ...
        "Name", "Simulation advantage: " + string(factorLabel), ...
        "NumberTitle", "off");
    axesHandle = axes(figureHandle);
    imageHandle = imagesc( ...
        axesHandle, frequency.frequencyHz, plotCenters, plotValues);
    imageHandle.AlphaData = displayMask;
    axesHandle.Color = [0.92 0.92 0.92];
    set(axesHandle, "YDir", "normal");
    xlim(axesHandle, simulationResults.settings.frequencyRangeHz);
    clim(axesHandle, [-colorLimit colorLimit]);
    colormap(axesHandle, misoAdvantageColormap());
    xlabel(axesHandle, "Frequency (Hz)");
    ylabel(axesHandle, getSimulationFactorAxisLabel( ...
        factorName, factorLabel));
    axesHandle.YTick = tickValues;
    axesHandle.YTickLabel = tickLabels;
    title(axesHandle, ...
        upper(pathway) + " pathway accuracy advantage by " + ...
        getSimulationFactorTitle(factorName, factorLabel));

    colorbarHandle = colorbar(axesHandle);
    colorbarHandle.Label.String = ...
        "log10(mean SISO error / mean MISO error)";
    colorbarHandle.Ticks = linspace(-colorLimit, colorLimit, 5);
    colorbarHandle.TickLabels = string(compose( ...
        "%.2g", colorbarHandle.Ticks));
    grid(axesHandle, "on");

    sourceData = struct();
    sourceData.frequencyMap = createFrequencyMapSourceTable( ...
        frequency.frequencyHz, summary);
    sourceData.metadata = table( ...
        string(pathway), string(factorName), string(groupingMode), ...
        summary.scoreVersion, colorLimit, minimumValidN, ...
        'VariableNames', { ...
            'Pathway', 'FactorName', 'GroupingMode', 'ScoreVersion', ...
            'ColorLimit', 'MinimumValidN'});

end

function sourceTable = createFrequencyMapSourceTable(frequencyHz, summary)
% createFrequencyMapSourceTable Store plotted cells in tidy form.

    factorValues = summary.factorCenters;
    numFactors = numel(factorValues);
    numFrequencies = numel(frequencyHz);
    sourceTable = table( ...
        repelem(factorValues(:), numFrequencies, 1), ...
        repelem(summary.factorLabels(:), numFrequencies, 1), ...
        repmat(frequencyHz(:), numFactors, 1), ...
        reshape(summary.sisoMean.', [], 1), ...
        reshape(summary.misoMean.', [], 1), ...
        reshape(summary.advantage.', [], 1), ...
        reshape(summary.sisoSD.', [], 1), ...
        reshape(summary.misoSD.', [], 1), ...
        reshape(summary.validN.', [], 1), ...
        reshape(summary.sisoValidN.', [], 1), ...
        reshape(summary.misoValidN.', [], 1), ...
        reshape(repelem(summary.groupN(:), numFrequencies), [], 1), ...
        reshape(summary.bootstrapSD.', [], 1), ...
        reshape(summary.ciLower.', [], 1), ...
        reshape(summary.ciUpper.', [], 1), ...
        repmat(summary.scoreVersion, numFactors*numFrequencies, 1), ...
        'VariableNames', { ...
            'FactorValue', 'FactorGroup', 'FrequencyHz', ...
            'SISOErrorMean', 'MISOErrorMean', 'Advantage', ...
            'SISOErrorSD', 'MISOErrorSD', 'PairedValidN', ...
            'SISOValidN', 'MISOValidN', 'GroupN', ...
            'BootstrapSD', 'CILower', 'CIUpper', 'ScoreVersion'});

end
