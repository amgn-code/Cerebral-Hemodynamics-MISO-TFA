function subjectResult = runNcSubjectBlockedValidation( ...
    subjectInfo, settings)
% runNcSubjectBlockedValidation Run blocked MISO/SISO validation for a file.

    subjectResult = createEmptyNcSubjectResult(subjectInfo);

    signalData = loadSubjectData(subjectInfo.SourceFile);
    processed = preprocessTfaSignals( ...
        signalData, settings.analysis.fsTarget, ...
        settings.analysis.preprocessing);

    blockSamples = round( ...
        settings.validation.blockLengthSeconds * settings.analysis.fsTarget);
    requiredSamples = blockSamples * settings.validation.numFolds;
    if numel(processed.map) < requiredSamples
        subjectResult.status = "InsufficientBlocks";
        subjectResult.statusMessage = sprintf( ...
            "Requires %d samples but only %d are available.", ...
            requiredSamples, numel(processed.map));
        subjectResult.recordingDurationSeconds = ...
            numel(processed.map) / settings.analysis.fsTarget;
        return
    end

    map = processed.map(1:requiredSamples);
    co2 = processed.co2(1:requiredSamples);
    cbv = processed.cbv(1:requiredSamples);

    foldSisoError = [];
    foldMisoError = [];
    frequencyHz = [];

    for foldIndex = 1:settings.validation.numFolds
        testStart = (foldIndex - 1) * blockSamples + 1;
        testEnd = foldIndex * blockSamples;
        testIndices = testStart:testEnd;
        trainingBlockIndices = setdiff( ...
            1:settings.validation.numFolds, foldIndex, "stable");

        trainingSpectra = estimateSeparateTrainingBlocks( ...
            map, co2, cbv, trainingBlockIndices, blockSamples, ...
            settings.analysis.fsTarget, settings.analysis.pwelch);
        validationSpectra = estimateWelchSpectra( ...
            map(testIndices), co2(testIndices), cbv(testIndices), ...
            settings.analysis.fsTarget, settings.analysis.pwelch);

        miso = runMISOTFA( ...
            trainingSpectra, settings.analysis.phase, ...
            settings.analysis.misoSolver);
        siso = runSISOTFA( ...
            trainingSpectra, settings.analysis.phase);

        [foldFrequencyHz, sisoError] = ...
            calculateFrequencyValidationPredictionError( ...
            validationSpectra, ...
            siso.map.transferFunction, ...
            zeros(size(siso.co2.transferFunction)), ...
            settings.analysis.frequencyRangeHz);
        [misoFrequencyHz, misoError] = ...
            calculateFrequencyValidationPredictionError( ...
            validationSpectra, ...
            miso.map.transferFunction, ...
            miso.co2.transferFunction, ...
            settings.analysis.frequencyRangeHz);

        if isempty(frequencyHz)
            frequencyHz = foldFrequencyHz;
            foldSisoError = NaN(numel(frequencyHz), ...
                settings.validation.numFolds);
            foldMisoError = NaN(numel(frequencyHz), ...
                settings.validation.numFolds);
        end

        if numel(foldFrequencyHz) ~= numel(frequencyHz) || ...
                any(foldFrequencyHz ~= frequencyHz) || ...
                numel(misoFrequencyHz) ~= numel(frequencyHz) || ...
                any(misoFrequencyHz ~= frequencyHz)
            error( ...
                "TFA:NCFrequencyGridMismatch", ...
                "Blocked validation folds did not use the same frequency grid.");
        end

        foldSisoError(:, foldIndex) = sisoError;
        foldMisoError(:, foldIndex) = misoError;
    end

    subjectResult.status = "Completed";
    subjectResult.statusMessage = "Completed";
    subjectResult.frequencyHz = frequencyHz;
    subjectResult.foldSisoError = foldSisoError;
    subjectResult.foldMisoError = foldMisoError;
    subjectResult.sisoError = mean(foldSisoError, 2, "omitnan");
    subjectResult.misoError = mean(foldMisoError, 2, "omitnan");
    subjectResult.advantage = calculateErrorAdvantage( ...
        subjectResult.sisoError, subjectResult.misoError, ...
        settings.errorFloor);
    subjectResult.numFoldsCompleted = settings.validation.numFolds;
    subjectResult.numValidFrequencyBins = nnz( ...
        isfinite(subjectResult.sisoError) & ...
        isfinite(subjectResult.misoError));
    subjectResult.recordingDurationSeconds = ...
        numel(processed.map) / settings.analysis.fsTarget;
    subjectResult.co2StartupRemovedSeconds = ...
        processed.co2Startup.removedDurationSeconds;
    subjectResult.welchWindowLengthSeconds = ...
        settings.analysis.pwelch.windowLengthSeconds;
    subjectResult.welchWindowCountForTraining = ...
        trainingSpectra.welchInfo.numWindows;

end

function trainingSpectra = estimateSeparateTrainingBlocks( ...
    map, co2, cbv, blockIndices, blockSamples, samplingFrequencyHz, ...
    welchSettings)
% estimateSeparateTrainingBlocks Average spectra without joining time blocks.

    blockSpectra = cell(numel(blockIndices), 1);
    for blockIndex = 1:numel(blockIndices)
        blockStart = (blockIndices(blockIndex) - 1) * blockSamples + 1;
        blockEnd = blockIndices(blockIndex) * blockSamples;
        blockSpectra{blockIndex} = estimateWelchSpectra( ...
            map(blockStart:blockEnd), ...
            co2(blockStart:blockEnd), ...
            cbv(blockStart:blockEnd), ...
            samplingFrequencyHz, welchSettings);
    end

    trainingSpectra = blockSpectra{1};
    trainingSpectra.map.power = mean( ...
        [blockSpectra{1}.map.power, blockSpectra{2}.map.power], 2);
    trainingSpectra.co2.power = mean( ...
        [blockSpectra{1}.co2.power, blockSpectra{2}.co2.power], 2);
    trainingSpectra.cbv.power = mean( ...
        [blockSpectra{1}.cbv.power, blockSpectra{2}.cbv.power], 2);
    trainingSpectra.cross.mapCo2 = mean( ...
        [blockSpectra{1}.cross.mapCo2, blockSpectra{2}.cross.mapCo2], 2);
    trainingSpectra.cross.co2Map = conj(trainingSpectra.cross.mapCo2);
    trainingSpectra.cross.mapCbv = mean( ...
        [blockSpectra{1}.cross.mapCbv, blockSpectra{2}.cross.mapCbv], 2);
    trainingSpectra.cross.co2Cbv = mean( ...
        [blockSpectra{1}.cross.co2Cbv, blockSpectra{2}.cross.co2Cbv], 2);

    trainingSpectra.welchInfo.numWindows = ...
        sum([blockSpectra{1}.welchInfo.numWindows, ...
        blockSpectra{2}.welchInfo.numWindows]);
    trainingSpectra.welchInfo.signalLengthSamples = ...
        sum([blockSpectra{1}.welchInfo.signalLengthSamples, ...
        blockSpectra{2}.welchInfo.signalLengthSamples]);
    trainingSpectra.welchInfo.signalDurationSeconds = ...
        trainingSpectra.welchInfo.signalLengthSamples / samplingFrequencyHz;
    trainingSpectra.welchInfo.isReadyForTFA = ...
        trainingSpectra.welchInfo.numWindows >= welchSettings.minimumWindows;

end

function subjectResult = createEmptyNcSubjectResult(subjectInfo)
% createEmptyNcSubjectResult Create a stable result shape for failed files.

    subjectResult.subjectID = string(subjectInfo.SubjectID);
    subjectResult.group = string(subjectInfo.Group);
    subjectResult.sourceFile = string(subjectInfo.SourceFile);
    subjectResult.status = "NotStarted";
    subjectResult.statusMessage = "";
    subjectResult.numFoldsCompleted = 0;
    subjectResult.numValidFrequencyBins = 0;
    subjectResult.recordingDurationSeconds = NaN;
    subjectResult.co2StartupRemovedSeconds = NaN;
    subjectResult.welchWindowLengthSeconds = NaN;
    subjectResult.welchWindowCountForTraining = NaN;
    subjectResult.frequencyHz = [];
    subjectResult.foldSisoError = [];
    subjectResult.foldMisoError = [];
    subjectResult.sisoError = [];
    subjectResult.misoError = [];
    subjectResult.advantage = [];

end
