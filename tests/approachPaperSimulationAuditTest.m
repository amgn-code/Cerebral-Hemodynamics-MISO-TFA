classdef approachPaperSimulationAuditTest < matlab.unittest.TestCase
    % approachPaperSimulationAuditTest Verify proof-run audit contracts.

    methods (TestClassSetup)
        function addProjectFolders(testCase)
            projectRoot = fileparts(fileparts(mfilename("fullpath")));
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture( ...
                    projectRoot, IncludingSubfolders=true));
        end
    end

    methods (Test)
        function balancedProofRunPassesCoreChecks(testCase)
            simulation = createSyntheticProofSimulation();

            audit = auditApproachPaperSimulation(simulation);

            testCase.verifyTrue(audit.allCoreChecksPass);
            testCase.verifyEqual( ...
                unique(audit.marginalBalance.ObservedN), 50);
            testCase.verifyEqual( ...
                unique(audit.pairwiseBalance.ObservedN), 10);
            testCase.verifyEqual( ...
                unique(audit.stability.CheckpointBlocks), [5; 8; 10]);
            testCase.verifyEqual( ...
                unique(audit.stability.FamiliesUsed), [125; 200; 250]);
        end

        function sparseRealizedCellsRemainVisible(testCase)
            simulation = createSyntheticProofSimulation();
            simulation.observations.FamilyInputCoherence(:) = 0.1;

            audit = auditApproachPaperSimulation(simulation);
            rows = audit.realizedBinOccupancy.Field == ...
                "FamilyInputCoherence";

            testCase.verifyEqual( ...
                audit.realizedBinOccupancy.FamilyN(rows), ...
                [250; 0; 0; 0; 0]);
            testCase.verifyEqual( ...
                audit.realizedBinOccupancy.MeetsDisplayMinimum(rows), ...
                [true; false; false; false; false]);
        end

        function assignedImbalanceFailsAudit(testCase)
            simulation = createSyntheticProofSimulation();
            simulation.familyDesign. ...
                TargetInputCoherenceLevel(1) = 6;
            simulation.familyDesign.TargetInputCoherence(1) = 0.99;

            audit = auditApproachPaperSimulation(simulation);
            marginalCheck = audit.overview.Check == ...
                "Assigned marginal balance";

            testCase.verifyFalse(audit.allCoreChecksPass);
            testCase.verifyFalse(audit.overview.Pass(marginalCheck));
            testCase.verifyTrue(any(~audit.marginalBalance.Pass));
        end

        function reportWriterCreatesReadableAudit(testCase)
            outputFolder = createTemporaryFolder(testCase);
            simulation = createSyntheticProofSimulation();
            audit = auditApproachPaperSimulation(simulation);

            reportFile = writeApproachPaperSimulationAudit( ...
                audit, outputFolder);
            reportText = string(fileread(reportFile));

            testCase.verifyTrue(isfile(reportFile));
            testCase.verifySubstring( ...
                reportText, "Presentation proof-of-concept evidence");
            testCase.verifySubstring( ...
                reportText, "Balanced-checkpoint stability");
            testCase.verifySubstring(reportText, "125");
            testCase.verifySubstring(reportText, "250");
        end
    end
end

function simulation = createSyntheticProofSimulation()
% createSyntheticProofSimulation Build a fast, complete audit fixture.

    settings = defaultKnownTruthSimulationSettings("proof250");
    design = createKnownTruthFamilyDesign(settings);
    plan = createKnownTruthObservationPlan(settings);
    numFamilies = height(design);
    numPlans = height(plan);
    numObservations = numFamilies*numPlans;
    familyId = repelem(design.FamilyID, numPlans);
    planId = repmat(plan.PlanID, numFamilies, 1);
    [~, familyLocation] = ismember(familyId, design.FamilyID);
    experiment = repmat(plan.Experiment, numFamilies, 1);
    durationSeconds = repmat(plan.DurationSeconds, numFamilies, 1);
    outputSnrDb = repmat(plan.OutputSNRdB, numFamilies, 1);
    mapInputSnrDb = repmat(plan.MAPInputSNRdB, numFamilies, 1);
    co2InputSnrDb = repmat(plan.CO2InputSNRdB, numFamilies, 1);
    alignmentErrorSeconds = repmat( ...
        plan.AlignmentErrorSeconds, numFamilies, 1);
    isReferenceObservation = repmat( ...
        plan.IsReferenceObservation, numFamilies, 1);
    isFamilyCharacterizationObservation = repmat( ...
        plan.IsFamilyCharacterizationObservation, numFamilies, 1);
    familyInputCoherence = design.TargetInputCoherence(familyLocation);
    familyPsdShapeOverlap = 0.1 + 0.2*( ...
        design.SpectralSimilarityLevel(familyLocation) - 1);
    familyContributionShare = 0.1 + 0.2*( ...
        design.PETCO2ToMAPFluctuationSDRatioLevel(familyLocation) - 1);
    baseMetric = 0.05 + 0.001*familyId;

    observations = table( ...
        familyId, planId, experiment, durationSeconds, outputSnrDb, ...
        mapInputSnrDb, co2InputSnrDb, alignmentErrorSeconds, ...
        isReferenceObservation, ...
        isFamilyCharacterizationObservation, ...
        familyInputCoherence, familyPsdShapeOverlap, ...
        familyContributionShare, ...
        1.2*baseMetric, baseMetric, 0.8*baseMetric, ...
        0.7*baseMetric, 0.6*baseMetric, ...
        1.3*baseMetric, 1.1*baseMetric, 0.9*baseMetric, ...
        0.75*baseMetric, 0.65*baseMetric, 0.5*baseMetric, ...
        'VariableNames', { ...
            'FamilyID', 'PlanID', 'Experiment', 'DurationSeconds', ...
            'OutputSNRdB', 'MAPInputSNRdB', 'CO2InputSNRdB', ...
            'AlignmentErrorSeconds', 'IsReferenceObservation', ...
            'IsFamilyCharacterizationObservation', ...
            'FamilyInputCoherence', 'FamilyPSDShapeOverlap', ...
            'FamilyPETCO2ContributionPowerShare', ...
            'MAPSISOComplexError', 'MAPMISOComplexError', ...
            'MAPComplexAdvantage', 'MAPGainAdvantage', ...
            'MAPPhaseAdvantage', 'CO2SISOComplexError', ...
            'CO2MISOComplexError', 'CO2ComplexAdvantage', ...
            'CO2GainAdvantage', 'CO2PhaseAdvantage', ...
            'PredictionAdvantage'});
    numRidgeRows = numFamilies*numel( ...
        settings.estimators.ridgeLambdas);
    numEstimatorRows = numFamilies*( ...
        numel(settings.estimatorSensitivity.windowLengthSeconds) + ...
        numel(settings.estimatorSensitivity.windowOverlap) + ...
        numel(settings.observations.durationSeconds)* ...
        numel(settings.estimatorSensitivity.windowLengthSeconds));

    simulation.settings = settings;
    simulation.familyDesign = design;
    simulation.observationPlan = plan;
    simulation.observations = observations;
    simulation.ridge = table(zeros(numRidgeRows, 1), ...
        'VariableNames', {'Placeholder'});
    simulation.estimatorSettings = table( ...
        zeros(numEstimatorRows, 1), ...
        'VariableNames', {'Placeholder'});
    simulation.numFamilies = numFamilies;
    simulation.numObservationPlans = numPlans;
    simulation.numObservations = numObservations;
    simulation.numEstimatorSettingAnalyses = numEstimatorRows;
    simulation.elapsedSeconds = 123.4;

end

function outputFolder = createTemporaryFolder(testCase)
% createTemporaryFolder Register cleanup for writer output.

    outputFolder = string(tempname());
    mkdir(outputFolder);
    testCase.addTeardown(@() rmdir(outputFolder, "s"));

end
