function factors = simulationFactors()
% simulationFactors Return the reviewed primary simulation factor schema.
%
% Primary levels are frozen from the Step 1 protocol and revised NC audit.
% Provenance stays beside every level so a stress condition cannot be
% mistaken for the central physiological operating range.

factors = struct( ...
    "name", {}, ...
    "units", {}, ...
    "role", {}, ...
    "levels", {}, ...
    "provenance", {}, ...
    "primary", {});

factors(end + 1) = makeFactor( ...
    "inputCoherence", "unitless", ...
    "MAP-CO2 input separability", [0 0.15 0.50 0.95], ...
    "NC bias-corrected 10th/50th/90th percentiles about 0.065/0.129/0.177; 0.15 is the NC operating point", true);
factors(end + 1) = makeFactor( ...
    "inputPhaseLagSeconds", "s", ...
    "MAP-CO2 input phase relationship", [-6 0 4], ...
    "NC-derived secondary levels; phase fits require at least five valid bins", false);
factors(end + 1) = makeFactor( ...
    "co2ToMapBandGainRatio", "unitless", ...
    "relative CO2 pathway strength", [0 0.25 1], ...
    "frozen mechanistic levels; report realized CBFV contribution share", true);
factors(end + 1) = makeFactor( ...
    "durationSeconds", "s", ...
    "recording length and estimator variance", [300 600], ...
    "methodological design level", true);
factors(end + 1) = makeFactor( ...
    "outputSnrDb", "dB", ...
    "CBFV output measurement quality", [Inf 10 0], ...
    "signal-shaped primary noise; white noise retained as robustness contrast", true);
factors(end + 1) = makeFactor( ...
    "mapMeasurementSnrDb", "dB", ...
    "MAP input measurement quality", [Inf 10 0], ...
    "frozen secondary engineering stress levels", false);
factors(end + 1) = makeFactor( ...
    "co2MeasurementSnrDb", "dB", ...
    "CO2 input measurement quality", [Inf 10 0], ...
    "frozen secondary engineering stress levels", false);

% Alignment is deliberately secondary. It represents acquisition error and
% must not be confused with the physiological input phase or pathway delay.
factors(end + 1) = makeFactor( ...
    "co2MeasurementAlignmentSeconds", "s", ...
    "recording alignment robustness", [-3 0 3], ...
    "secondary robustness stress levels", false);

end

function factor = makeFactor( ...
    name, units, role, levels, provenance, primary)

factor.name = string(name);
factor.units = string(units);
factor.role = string(role);
factor.levels = levels;
factor.provenance = string(provenance);
factor.primary = logical(primary);

end
