function familyDesign = createKnownTruthFamilyDesign(settings)
% createKnownTruthFamilyDesign Create balanced family-level physiology.
%
% Named physiological factors use either marginal balancing or complete
% pairwise-balanced five-level blocks. Time constants remain continuous
% nuisance variables. Input phase is explicit so it cannot be confused with
% pathway delay or measurement alignment.

    designMode = string(settings.families.designMode);
    if lower(designMode) == "fullfactorial"
        valueSetLengths = [ ...
            numel(settings.families.targetCoherenceValues), ...
            numel(settings.families.spectralSimilarityValues), ...
            numel(settings.families.petco2ToMapFluctuationSdRatioValues), ...
            numel(settings.families.petco2ToMapBandGainRatioValues), ...
            numel(settings.families.co2DelaySecondsValues), ...
            numel(settings.families.inputPhaseLagSecondsValues)];
        numFamilies = prod(valueSetLengths)*settingsRepetitions( ...
            settings.families);
    else
        if ~isfield(settings.families, "numFamilies")
            error("TFA:MissingFamilyCount", ...
                "Non-factorial designs must declare families.numFamilies.");
        end
        numFamilies = settings.families.numFamilies;
        validateattributes( ...
            numFamilies, {'numeric'}, ...
            {'scalar', 'integer', 'positive', 'finite'});
    end
    validateFamilyFactorValues(settings.families);

    [factorValues, factorLevelIndices, designBlockId, designBaseRow] = ...
        createFamilyFactorAssignments( ...
        settings.families, numFamilies, settings.randomSeed);
    targetCoherence = factorValues(:,1);
    spectralSimilarity = factorValues(:,2);
    petco2ToMapFluctuationSdRatio = factorValues(:,3);
    petco2ToMapBandGainRatio = factorValues(:,4);
    co2DelaySeconds = factorValues(:,5);
    inputPhaseLagSeconds = factorValues(:,6);
    mapTimeConstantSeconds = sampleLinearRange( ...
        numFamilies, ...
        settings.families.mapPathwayTimeConstantRange, ...
        settings.randomSeed, 17);
    co2TimeConstantSeconds = sampleLinearRange( ...
        numFamilies, ...
        settings.families.co2PathwayTimeConstantRange, ...
        settings.randomSeed, 31);

    fs = settings.samplingFrequencyHz;
    co2DelaySeconds = round(co2DelaySeconds*fs)/fs;

    familyId = (1:numFamilies)';
    scenarioId = familyId;
    % A family owns its random stream. Adding families therefore appends new
    % realizations without changing the already assigned prefix.
    familySeed = settings.randomSeed + 7919*familyId;

    designedSpectralOverlap = NaN(numFamilies, 1);
    for familyIndex = 1:numFamilies
        scenario = makeScenario( ...
            targetCoherence(familyIndex), ...
            spectralSimilarity(familyIndex), ...
            petco2ToMapFluctuationSdRatio(familyIndex), ...
            petco2ToMapBandGainRatio(familyIndex), ...
            co2DelaySeconds(familyIndex), ...
            inputPhaseLagSeconds(familyIndex), ...
            mapTimeConstantSeconds(familyIndex), ...
            co2TimeConstantSeconds(familyIndex));
        frequencyHz = linspace( ...
            settings.frequencyRangeHz(1), ...
            settings.frequencyRangeHz(2), 1024)';
        shapes = createKnownTruthInputSpectra( ...
            frequencyHz, scenario, settings);
        designedSpectralOverlap(familyIndex) = ...
            calculatePSDShapeOverlap( ...
                shapes.mapPower, shapes.co2Power);
    end

    familyDesign = table( ...
        familyId, scenarioId, familySeed, ...
        designBlockId, designBaseRow, ...
        factorLevelIndices(:,1), factorLevelIndices(:,2), ...
        factorLevelIndices(:,3), factorLevelIndices(:,4), ...
        factorLevelIndices(:,5), ...
        factorLevelIndices(:,6), ...
        targetCoherence, ...
        spectralSimilarity, designedSpectralOverlap, ...
        petco2ToMapFluctuationSdRatio, petco2ToMapBandGainRatio, ...
        co2DelaySeconds, inputPhaseLagSeconds, ...
        mapTimeConstantSeconds, co2TimeConstantSeconds, ...
        'VariableNames', { ...
            'FamilyID', 'ScenarioID', 'FamilySeed', ...
            'DesignBlockID', 'DesignBaseRow', ...
            'TargetInputCoherenceLevel', ...
            'SpectralSimilarityLevel', ...
            'PETCO2ToMAPFluctuationSDRatioLevel', ...
            'PETCO2ToMAPBandGainRatioLevel', ...
            'CO2DelayLevel', ...
            'InputPhaseLagLevel', ...
            'TargetInputCoherence', 'SpectralSimilarityControl', ...
            'DesignedPSDShapeOverlap', ...
            'PETCO2ToMAPFluctuationSDRatio', ...
            'PETCO2ToMAPBandGainRatio', 'CO2DelaySeconds', ...
            'InputPhaseLagSeconds', ...
            'MAPPathwayTimeConstantSeconds', ...
            'CO2PathwayTimeConstantSeconds'});

end

function [factorValues, levelIndices, designBlockId, designBaseRow] = ...
    createFamilyFactorAssignments(families, numFamilies, randomSeed)
% createFamilyFactorAssignments Assign the intrinsic family factor values.

    valueSets = { ...
        double(families.targetCoherenceValues(:)); ...
        double(families.spectralSimilarityValues(:)); ...
        double(families.petco2ToMapFluctuationSdRatioValues(:)); ...
        double(families.petco2ToMapBandGainRatioValues(:)); ...
        double(families.co2DelaySecondsValues(:)); ...
        double(families.inputPhaseLagSecondsValues(:))};
    numFactors = numel(valueSets);
    designMode = "marginalBalanced";
    if isfield(families, "designMode")
        designMode = string(families.designMode);
    end

    factorValues = zeros(numFamilies, numFactors);
    levelIndices = zeros(numFamilies, numFactors);
    designBlockId = NaN(numFamilies, 1);
    designBaseRow = NaN(numFamilies, 1);

    if lower(designMode) == "fullfactorial"
        [factorValues, levelIndices, designBlockId, designBaseRow] = ...
            createFullFactorialAssignments(valueSets, numFamilies, ...
            settingsRepetitions(families));
        return
    end

    if lower(designMode) == "pairwisefivelevel"
        numLevels = cellfun(@numel, valueSets);
        % The proof design balances the five original physiology factors.
        % Input phase is an explicit sixth factor, but is fixed at zero until
        % its empirical levels are confirmed. Preserve that fixed column
        % without pretending that the five-factor orthogonal array balances
        % a sixth varying factor.
        hasFixedPhaseColumn = numFactors == 6 && numLevels(6) == 1;
        if hasFixedPhaseColumn
            pairwiseValueSets = valueSets(1:5);
            pairwiseNumLevels = numLevels(1:5);
        else
            pairwiseValueSets = valueSets;
            pairwiseNumLevels = numLevels;
        end
        if any(pairwiseNumLevels ~= 5) || ...
                (numFactors ~= 5 && ~hasFixedPhaseColumn)
            error( ...
                "TFA:PairwiseDesignRequiresFiveLevels", ...
                ['Every assigned family factor must contain exactly five ' ...
                 'levels when designMode is "pairwiseFiveLevel".']);
        end
        [levelIndices, designBlockId, designBaseRow] = ...
            createPairwiseBalancedFiveLevelDesign( ...
                numFamilies, randomSeed);
        for factorIndex = 1:5
            currentValues = pairwiseValueSets{factorIndex};
            factorValues(:,factorIndex) = ...
                currentValues(levelIndices(:,factorIndex));
        end
        if hasFixedPhaseColumn
            factorValues(:,6) = valueSets{6};
            levelIndices(:,6) = 1;
        end
        return
    end

    if lower(designMode) ~= "marginalbalanced"
        error( ...
            "TFA:UnknownFamilyDesignMode", ...
            ['families.designMode must be "marginalBalanced", ' ...
             '"fullFactorial", or "pairwiseFiveLevel".']);
    end
    for factorIndex = 1:numFactors
        currentValues = valueSets{factorIndex};
        assignedValues = createStableBalancedFamilyLevels( ...
            currentValues, numFamilies, factorIndex);
        [isFound, currentIndices] = ismember( ...
            assignedValues, currentValues);
        if ~all(isFound)
            error( ...
                "TFA:InvalidMarginalFamilyAssignment", ...
                "A balanced family value has no matching level index.");
        end
        factorValues(:,factorIndex) = assignedValues;
        levelIndices(:,factorIndex) = currentIndices;
    end

end

function validateFamilyFactorValues(families)
% validateFamilyFactorValues Give clear errors for editable main settings.

    validateattributes( ...
        families.targetCoherenceValues, {'numeric'}, ...
        {'nonempty', 'finite', '>=', 0, '<=', 1});
    validateattributes( ...
        families.spectralSimilarityValues, {'numeric'}, ...
        {'nonempty', 'finite', '>=', 0, '<=', 1});
    validateattributes( ...
        families.petco2ToMapFluctuationSdRatioValues, {'numeric'}, ...
        {'nonempty', 'finite', 'positive'});
    validateattributes( ...
        families.petco2ToMapBandGainRatioValues, {'numeric'}, ...
        {'nonempty', 'finite', 'nonnegative'});
    validateattributes( ...
        families.co2DelaySecondsValues, {'numeric'}, ...
        {'nonempty', 'finite', 'nonnegative'});
    validateattributes( ...
        families.inputPhaseLagSecondsValues, {'numeric'}, ...
        {'nonempty', 'finite'});
    factorFields = [ ...
        "targetCoherenceValues"
        "spectralSimilarityValues"
        "petco2ToMapFluctuationSdRatioValues"
        "petco2ToMapBandGainRatioValues"
        "co2DelaySecondsValues"
        "inputPhaseLagSecondsValues"];
    for fieldIndex = 1:numel(factorFields)
        values = families.(factorFields(fieldIndex));
        if numel(unique(values)) ~= numel(values)
            error( ...
                "TFA:DuplicateFamilyFactorLevel", ...
                "Assigned family factor levels must be unique.");
        end
    end

end

function [factorValues, levelIndices, designBlockId, designBaseRow] = ...
    createFullFactorialAssignments(valueSets, numFamilies, repetitions)
% createFullFactorialAssignments Create repeated rows for every combination.

    numLevels = cellfun(@numel, valueSets);
    numCombinations = prod(numLevels);
    expectedFamilies = numCombinations*repetitions;
    if numFamilies ~= expectedFamilies
        error( ...
            "TFA:FullFactorialRequiresCompleteDesign", ...
            ['Full-factorial design requires %d families for %d ' ...
             'repetition(s), but numFamilies is %d.'], ...
            expectedFamilies, repetitions, numFamilies);
    end

    gridValues = cell(1, numel(valueSets));
    [gridValues{:}] = ndgrid(valueSets{:});
    baseValues = zeros(numCombinations, numel(valueSets));
    baseLevels = zeros(numCombinations, numel(valueSets));
    for factorIndex = 1:numel(valueSets)
        baseValues(:, factorIndex) = gridValues{factorIndex}(:);
        [~, baseLevels(:, factorIndex)] = ismember( ...
            baseValues(:, factorIndex), valueSets{factorIndex});
    end

    factorValues = repmat(baseValues, repetitions, 1);
    levelIndices = repmat(baseLevels, repetitions, 1);
    designBlockId = repelem((1:repetitions)', numCombinations);
    designBlockId = designBlockId(:);
    designBaseRow = repmat((1:numCombinations)', repetitions, 1);

end

function repetitions = settingsRepetitions(families)
% settingsRepetitions Return the explicit full-factorial repetition count.

    repetitions = 1;
    if isfield(families, "repetitionsPerCondition")
        repetitions = families.repetitionsPerCondition;
    end
    validateattributes( ...
        repetitions, {'numeric'}, ...
        {'scalar', 'integer', 'positive', 'finite'});

end

function values = sampleLinearRange( ...
    numValues, range, randomSeed, streamOffset)
% sampleLinearRange Draw one reproducible nuisance value per family.

    values = NaN(numValues, 1);
    for familyIndex = 1:numValues
        familyStream = RandStream("threefry", ...
            "Seed", randomSeed + streamOffset + 7919*familyIndex);
        values(familyIndex) = range(1) + ...
            familyStream.rand()*(range(2) - range(1));
    end

end

function levels = createStableBalancedFamilyLevels( ...
    allowedValues, numFamilies, factorIndex)
% createStableBalancedFamilyLevels Assign levels without N-dependent shuffles.

    allowedValues = allowedValues(:);
    numLevels = numel(allowedValues);
    indices = mod((0:(numFamilies - 1))' + factorIndex - 1, numLevels) + 1;
    levels = allowedValues(indices);

end

function scenario = makeScenario( ...
    targetCoherence, spectralSimilarity, ...
    petco2ToMapFluctuationSdRatio, ...
    petco2ToMapBandGainRatio, co2DelaySeconds, inputPhaseLagSeconds, ...
    mapTimeConstantSeconds, ...
    co2TimeConstantSeconds)
% makeScenario Make the small struct used by the spectrum helper.

    scenario.targetInputCoherence = targetCoherence;
    scenario.spectralSimilarityControl = spectralSimilarity;
    scenario.petco2ToMapFluctuationSdRatio = ...
        petco2ToMapFluctuationSdRatio;
    scenario.petco2ToMapBandGainRatio = ...
        petco2ToMapBandGainRatio;
    scenario.co2DelaySeconds = co2DelaySeconds;
    scenario.inputPhaseLagSeconds = inputPhaseLagSeconds;
    scenario.mapPathwayTimeConstantSeconds = ...
        mapTimeConstantSeconds;
    scenario.co2PathwayTimeConstantSeconds = ...
        co2TimeConstantSeconds;

end
