function observationPlan = createKnownTruthObservationPlan(settings)
% createKnownTruthObservationPlan List all paired observation variants.
%
% The main experiment crosses duration with CBFV output SNR. Secondary
% experiments vary input measurement noise and CO2 alignment at one
% user-selected standard duration and output SNR.

    durations = settings.observations.durationSeconds(:);
    outputSnrValues = settings.observations.outputSnrDb(:);
    referenceDuration = ...
        settings.observations.referenceDurationSeconds;
    validateattributes(referenceDuration, {'numeric'}, ...
        {'scalar', 'positive', 'finite'});
    characterizationDuration = max([durations; referenceDuration]);
    referenceOutputSnr = ...
        settings.observations.referenceOutputSnrDb;
    primaryNoiseSpectrum = string(settings.observations.noiseSpectrum);
    experimentSet = "all";
    if isfield(settings.observations, "experimentSet")
        experimentSet = lower(string(settings.observations.experimentSet));
    end
    validSets = ["all" "core" "reference" "inputnoise" ...
        "alignment" "whitenoise"];
    if ~isscalar(experimentSet) || ~ismember(experimentSet, validSets)
        error("TFA:UnknownSimulationExperimentSet", ...
            "experimentSet must be all, core, reference, inputNoise, alignment, or whiteNoise.");
    end

    if ~ismember(referenceOutputSnr, outputSnrValues)
        % Keep the workflow easy to edit. If the user changes the SNR
        % sweep but forgets to change the reference, use the closest
        % available finite value.
        finiteIndices = find(isfinite(outputSnrValues));
        if isempty(finiteIndices)
            referenceOutputSnr = outputSnrValues(1);
        else
            [~, nearestIndex] = min(abs( ...
                outputSnrValues(finiteIndices) - referenceOutputSnr));
            referenceOutputSnr = ...
                outputSnrValues(finiteIndices(nearestIndex));
        end
    end

    rows = cell(0, 1);

    if ismember(experimentSet, ["all" "core"])
        for durationIndex = 1:numel(durations)
            for snrIndex = 1:numel(outputSnrValues)
                rows{end + 1,1} = makePlanRow( ...
                    "Main", durations(durationIndex), ...
                    outputSnrValues(snrIndex), Inf, Inf, 0, ...
                    primaryNoiseSpectrum); %#ok<AGROW>
            end
        end
        hasReferenceDuration = any(durations == referenceDuration);
        if ~hasReferenceDuration
            for snrIndex = 1:numel(outputSnrValues)
                rows{end + 1,1} = makePlanRow( ...
                    "Main", referenceDuration, ...
                    outputSnrValues(snrIndex), Inf, Inf, 0, ...
                    primaryNoiseSpectrum); %#ok<AGROW>
            end
        end
    elseif experimentSet == "reference"
        rows{end + 1,1} = makePlanRow( ...
            "Main", referenceDuration, referenceOutputSnr, ...
            Inf, Inf, 0, primaryNoiseSpectrum);
    end

    % A long, noise-free observation defines the intrinsic realized
    % properties of each family. Add it if it is absent from the main grid.
    hasCleanCharacterization = false;
    if ~isempty(rows)
        existingRows = vertcat(rows{:});
        hasCleanCharacterization = any( ...
            existingRows.DurationSeconds == characterizationDuration & ...
            isinf(existingRows.OutputSNRdB) & ...
            isinf(existingRows.MAPInputSNRdB) & ...
            isinf(existingRows.CO2InputSNRdB) & ...
            existingRows.AlignmentErrorSeconds == 0);
    end
    if ~hasCleanCharacterization
        rows{end + 1,1} = makePlanRow( ...
            "Family characterization", characterizationDuration, ...
            Inf, Inf, Inf, 0, primaryNoiseSpectrum);
    end

    if settings.observations.runInputNoiseExperiment && ...
            ismember(experimentSet, ["all" "inputnoise"])
        inputSnrValues = ...
            settings.observations.inputNoiseSnrDb(:);
        for snrIndex = 1:numel(inputSnrValues)
            rows{end + 1,1} = makePlanRow( ...
                "MAP input noise", referenceDuration, ...
                referenceOutputSnr, inputSnrValues(snrIndex), ...
                Inf, 0, primaryNoiseSpectrum); %#ok<AGROW>
            rows{end + 1,1} = makePlanRow( ...
                "CO2 input noise", referenceDuration, ...
                referenceOutputSnr, Inf, ...
                inputSnrValues(snrIndex), 0, ...
                primaryNoiseSpectrum); %#ok<AGROW>
        end
    end

    if settings.observations.runAlignmentExperiment && ...
            ismember(experimentSet, ["all" "alignment"])
        alignmentErrors = ...
            settings.observations.alignmentErrorSeconds(:);
        for alignmentIndex = 1:numel(alignmentErrors)
            rows{end + 1,1} = makePlanRow( ...
                "Alignment", referenceDuration, ...
                referenceOutputSnr, Inf, Inf, ...
                alignmentErrors(alignmentIndex), ...
                primaryNoiseSpectrum); %#ok<AGROW>
        end
    end

    if settings.observations.runWhiteNoiseRobustness && ...
            ismember(experimentSet, ["all" "whitenoise"]) && ...
            primaryNoiseSpectrum ~= "white"
        finiteOutputSnr = outputSnrValues(isfinite(outputSnrValues));
        for snrIndex = 1:numel(finiteOutputSnr)
            rows{end + 1,1} = makePlanRow( ...
                "White output noise", referenceDuration, ...
                finiteOutputSnr(snrIndex), Inf, Inf, 0, "white"); %#ok<AGROW>
        end
    end

    observationPlan = vertcat(rows{:});
    observationPlan.PlanID = (1:height(observationPlan))';

    observationPlan.IsReferenceObservation = ...
        observationPlan.Experiment == "Main" & ...
        observationPlan.DurationSeconds == referenceDuration & ...
        observationPlan.OutputSNRdB == referenceOutputSnr;
    observationPlan.IsFamilyCharacterizationObservation = ...
        ismember(observationPlan.Experiment, ...
            ["Main", "Family characterization"]) & ...
        observationPlan.DurationSeconds == characterizationDuration & ...
        isinf(observationPlan.OutputSNRdB) & ...
        isinf(observationPlan.MAPInputSNRdB) & ...
        isinf(observationPlan.CO2InputSNRdB) & ...
        observationPlan.AlignmentErrorSeconds == 0;

    observationPlan = movevars( ...
        observationPlan, "PlanID", "Before", 1);

end

function row = makePlanRow( ...
    experiment, durationSeconds, outputSnrDb, mapInputSnrDb, ...
    co2InputSnrDb, alignmentErrorSeconds, noiseSpectrum)
% makePlanRow Create one-row table for a single observation variant.

    row = table( ...
        string(experiment), durationSeconds, outputSnrDb, ...
        mapInputSnrDb, co2InputSnrDb, alignmentErrorSeconds, ...
        string(noiseSpectrum), ...
        'VariableNames', { ...
            'Experiment', 'DurationSeconds', 'OutputSNRdB', ...
            'MAPInputSNRdB', 'CO2InputSNRdB', ...
            'AlignmentErrorSeconds', 'NoiseSpectrum'});

end
