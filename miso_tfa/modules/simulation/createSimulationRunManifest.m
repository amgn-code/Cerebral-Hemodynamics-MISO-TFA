function manifest = createSimulationRunManifest( ...
    simulationResults, outputSettings, maps)
% createSimulationRunManifest Record what is needed to reconstruct a run.
%
% The human-readable summary is paired with the exact settings structure
% in the MAT export. Git information is included when the project is
% running from a repository.

    if nargin < 3
        maps = struct( ...
            "name", {}, "kind", {}, ...
            "variableName", {}, "label", {});
    end

    [gitCommit, gitWorkingTreeClean] = getGitState();
    settings = simulationResults.settings;
    realizationLengthSeconds = NaN;
    if isfield(settings, "generator") && ...
            isfield(settings.generator, "realizationLengthSeconds")
        realizationLengthSeconds = settings.generator.realizationLengthSeconds;
    end
    createdAt = datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ss'Z'");

    parameter = [ ...
        "SchemaVersion"; ...
        "CreatedUTC"; ...
        "MATLABRelease"; ...
        "MATLABVersion"; ...
        "ProfileName"; ...
        "SimulationRandomSeed"; ...
        "OutputBootstrapSeed"; ...
        "OutputBootstrapSamples"; ...
        "OutputConfidenceLevel"; ...
        "ResolvedAdvantageColorLimit"; ...
        "SamplingFrequencyHz"; ...
        "FrequencyRangeHz"; ...
        "PathwayCalibrationBandHz"; ...
        "InputSpectrumModel"; ...
        "InputSpectrumRolloffHz"; ...
        "InputSpectrumExponent"; ...
        "OutputNoiseSpectrum"; ...
        "WelchSegmentDetrend"; ...
        "RealizationLengthSeconds"; ...
        "NumFamilies"; ...
        "NumObservationPlans"; ...
        "NumObservations"; ...
        "AdvantageDefinition"; ...
        "GitCommit"; ...
        "GitWorkingTreeClean"];
    value = [ ...
        "simulation-output-v1"; ...
        string(createdAt); ...
        string(version("-release")); ...
        string(version); ...
        string(settings.profileName); ...
        string(settings.randomSeed); ...
        string(outputSettings.bootstrap.randomSeed); ...
        string(outputSettings.bootstrap.numSamples); ...
        string(outputSettings.bootstrap.confidenceLevel); ...
        string(getResolvedColorLimit(outputSettings)); ...
        string(settings.samplingFrequencyHz); ...
        string(mat2str(settings.frequencyRangeHz)); ...
        string(mat2str(settings.pathways.calibrationBandHz)); ...
        string(settings.inputs.spectrumModel); ...
        string(settings.inputs.rolloffFrequencyHz); ...
        string(settings.inputs.rolloffExponent); ...
        string(settings.observations.noiseSpectrum); ...
        "linear"; ...
        string(realizationLengthSeconds); ...
        string(simulationResults.numFamilies); ...
        string(simulationResults.numObservationPlans); ...
        string(simulationResults.numObservations); ...
        "truthRecoveryAdvantage: log10(mean SISO truth error / mean MISO truth error)"; ...
        gitCommit; ...
        string(gitWorkingTreeClean)];

    manifest.schemaVersion = "simulation-output-v1";
    manifest.createdUTC = string(createdAt);
    manifest.summary = table(parameter, value, ...
        VariableNames=["Parameter", "Value"]);
    manifest.settings = settings;
    manifest.outputSettings = outputSettings;
    manifest.mapIndex = createMapIndex(maps);
    manifest.gitCommit = gitCommit;
    manifest.gitWorkingTreeClean = gitWorkingTreeClean;

end

function colorLimit = getResolvedColorLimit(outputSettings)
% getResolvedColorLimit Return the actual pooled limit when available.

    if isfield(outputSettings, "resolvedAdvantageColorLimit")
        colorLimit = outputSettings.resolvedAdvantageColorLimit;
    else
        colorLimit = outputSettings.advantageColorLimit;
    end

end

function mapIndex = createMapIndex(maps)
% createMapIndex List every returned frequency heatmap.

    numMaps = numel(maps);
    name = strings(numMaps, 1);
    kind = strings(numMaps, 1);
    variableName = strings(numMaps, 1);
    label = strings(numMaps, 1);
    for mapNumber = 1:numMaps
        name(mapNumber) = maps(mapNumber).name;
        kind(mapNumber) = maps(mapNumber).kind;
        variableName(mapNumber) = maps(mapNumber).variableName;
        label(mapNumber) = maps(mapNumber).label;
    end

    mapIndex = table(name, kind, variableName, label, ...
        VariableNames=["Name", "Kind", "VariableName", "Label"]);

end

function [commit, workingTreeClean] = getGitState()
% getGitState Return repository identity when Git is available.

    projectRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
    [rootStatus, rootText] = system(sprintf( ...
        'git -C "%s" rev-parse --show-toplevel', projectRoot));
    if rootStatus ~= 0
        commit = "unavailable";
        workingTreeClean = false;
        return
    end
    repositoryRoot = strtrim(rootText);
    commitCommand = sprintf( ...
        'git -C "%s" rev-parse HEAD', repositoryRoot);
    [commitStatus, commitText] = system(commitCommand);
    if commitStatus ~= 0
        commit = "unavailable";
        workingTreeClean = false;
        return
    end

    statusCommand = sprintf( ...
        'git -C "%s" status --porcelain -- "%s"', ...
        repositoryRoot, projectRoot);
    [statusCode, statusText] = system(statusCommand);
    commit = string(strtrim(commitText));
    workingTreeClean = statusCode == 0 && strlength(strtrim(statusText)) == 0;

end
