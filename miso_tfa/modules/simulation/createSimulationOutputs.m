function outputs = createSimulationOutputs(simulationResults, outputSettings)
% createSimulationOutputs Build the primary and diagnostic simulation maps.
%
% Four maps use the frozen primary factors. Two maps use frequency-wise
% coherence diagnostics and are kept separate from the primary figure set.
% Each map retains the plotted advantage and its underlying paired SISO and
% MISO errors in a table.

    if nargin < 2 || isempty(outputSettings)
        outputSettings = defaultSimulationOutputSettings();
    else
        outputSettings = completeSimulationOutputSettings(outputSettings);
    end
    validateSimulationResults(simulationResults);

    observations = simulationResults.observations;
    referenceDuration = ...
        simulationResults.settings.observations.referenceDurationSeconds;
    referenceOutputSnr = ...
        simulationResults.settings.observations.referenceOutputSnrDb;
    referenceCoherence = getReferenceFamilyValue( ...
        simulationResults.settings, "referenceTargetInputCoherence", 0.50);
    referencePathwayRatio = getReferenceFamilyValue( ...
        simulationResults.settings, ...
        "referencePETCO2ToMAPBandGainRatio", 1);

    if ismember("IsMainExperiment", ...
            string(observations.Properties.VariableNames))
        mainRows = observations.IsMainExperiment;
    else
        mainRows = true(height(observations), 1);
    end

    outputs = buildOutputs(simulationResults, observations, mainRows, ...
        referenceDuration, referenceOutputSnr, referenceCoherence, ...
        referencePathwayRatio, outputSettings);

end

function outputs = buildOutputs(simulationResults, observations, mainRows, ...
    referenceDuration, referenceOutputSnr, referenceCoherence, ...
    referencePathwayRatio, outputSettings)
% buildOutputs Create assigned-factor and diagnostic maps.

    factorNames = [ ...
        "TargetInputCoherence"; ...
        "AssignedPETCO2ToMAPBandGainRatio"; ...
        "DurationSeconds"; ...
        "OutputSNRdB"];
    factorLabels = [ ...
        "MAP-CO2 input coherence"; ...
        "Assigned CO2-to-MAP pathway ratio"; ...
        "Recording duration (s)"; ...
        "CBFV output SNR (dB)"];
    mapNames = [ ...
        "input_coherence"; "co2_pathway_ratio"; ...
        "recording_duration"; "output_snr"];

    diagnosticNames = [ ...
        "multipleMinusMapCoherence"; ...
        "multipleMinusPartialMapCoherence"];
    diagnosticLabels = [ ...
        "MISO minus MAP pairwise coherence"; ...
        "MISO minus MAP partial coherence given CO2"];
    diagnosticMapNames = [ ...
        "miso_minus_map_pairwise_coherence"; ...
        "miso_minus_map_partial_coherence"];

    numPrimaryMaps = numel(factorNames);
    numDiagnosticMaps = numel(diagnosticNames);
    numMaps = numPrimaryMaps + numDiagnosticMaps;
    allowReferenceFallback = ismember( ...
        lower(string(simulationResults.settings.profileName)), ...
        ["quick" "designsmoke"]);
    maps = repmat(emptyMap(), numMaps, 1);
    plotSettings = outputSettings;
    if ~outputSettings.createFigures
        plotSettings.visible = "off";
    end
    colorLimit = resolveColorLimit( ...
        simulationResults, observations, mainRows, factorNames, ...
        referenceDuration, referenceOutputSnr, referenceCoherence, ...
        referencePathwayRatio, allowReferenceFallback, outputSettings);
    outputSettings.resolvedAdvantageColorLimit = colorLimit;

    for factorIndex = 1:numPrimaryMaps
        factorName = factorNames(factorIndex);
        dataRows = selectRowsWithFallback(observations, mainRows, factorName, ...
            referenceDuration, referenceOutputSnr, referenceCoherence, ...
            referencePathwayRatio, allowReferenceFallback);
        if ~any(dataRows)
            error("TFA:MissingSimulationOutputRows", ...
                "No reference rows are available for %s.", factorName);
        end

        [figureHandle, sourceData] = plotSimpleSimulationFrequencyMap( ...
            simulationResults, dataRows, factorName, ...
            factorLabels(factorIndex), "exact", "map", ...
            colorLimit, plotSettings);
        maps(factorIndex) = makeMap( ...
            mapNames(factorIndex), "assigned factor", factorName, ...
            factorLabels(factorIndex), figureHandle, sourceData, ...
            createSimulationCompanionTables( ...
                simulationResults, dataRows, factorName, "exact", "map"));
    end

    diagnosticRows = mainRows & ...
        observations.DurationSeconds == referenceDuration & ...
        observations.OutputSNRdB == referenceOutputSnr & ...
        observations.TargetInputCoherence == referenceCoherence & ...
        observations.AssignedPETCO2ToMAPBandGainRatio == ...
        referencePathwayRatio;
    if ~any(diagnosticRows)
        if ~allowReferenceFallback
            error("TFA:MissingProductionReferenceSlice", ...
                "The declared diagnostic reference slice is absent.");
        end
        diagnosticRows = mainRows & ...
            observations.DurationSeconds == referenceDuration & ...
            observations.OutputSNRdB == referenceOutputSnr;
    end
    for diagnosticIndex = 1:numel(diagnosticNames)
        diagnosticName = diagnosticNames(diagnosticIndex);
        [figureHandle, sourceData] = plotSimpleSimulationDiagnosticMap( ...
            simulationResults, diagnosticRows, diagnosticName, ...
            diagnosticLabels(diagnosticIndex), "map", ...
            colorLimit, ...
            outputSettings.diagnosticBinEdges, plotSettings);
        mapIndex = numPrimaryMaps + diagnosticIndex;
        maps(mapIndex) = makeMap( ...
            diagnosticMapNames(diagnosticIndex), "diagnostic", ...
            diagnosticName, diagnosticLabels(diagnosticIndex), ...
            figureHandle, sourceData);
    end

    if ~outputSettings.createFigures
        for mapIndex = 1:numel(maps)
            close(maps(mapIndex).figureHandle);
            maps(mapIndex).figureHandle = [];
        end
    end

    outputs.maps = maps;
    outputs.primaryMaps = maps(1:numPrimaryMaps);
    outputs.diagnosticMaps = maps(numPrimaryMaps + 1:end);
    outputs.manifest = createSimulationRunManifest( ...
        simulationResults, outputSettings, maps);
    outputs.settings = outputSettings;
    outputs.referenceDurationSeconds = referenceDuration;
    outputs.referenceOutputSnrDb = referenceOutputSnr;

end

function colorLimit = resolveColorLimit( ...
    simulationResults, observations, mainRows, factorNames, ...
    referenceDuration, referenceOutputSnr, referenceCoherence, ...
    referencePathwayRatio, allowReferenceFallback, outputSettings)
% resolveColorLimit Use one symmetric limit for all primary heatmaps.

    if isfinite(outputSettings.advantageColorLimit)
        colorLimit = outputSettings.advantageColorLimit;
        return
    end

    values = [];
    bootstrapSettings = outputSettings.bootstrap;
    bootstrapSettings.enabled = false;
    for factorIndex = 1:numel(factorNames)
        factorName = factorNames(factorIndex);
        dataRows = selectRowsWithFallback(observations, mainRows, factorName, ...
            referenceDuration, referenceOutputSnr, referenceCoherence, ...
            referencePathwayRatio, allowReferenceFallback);
        factorValues = observations.(factorName)(dataRows);
        observationColumns = observations.ObservationID(dataRows);
        pathwayResults = simulationResults.frequency.map;
        summary = summarizeSimulationFrequencyAdvantage( ...
            factorValues, ...
            pathwayResults.sisoComplexError(:, observationColumns), ...
            pathwayResults.misoComplexError(:, observationColumns), ...
            factorName, "exact", simulationResults.settings.grouping, ...
            bootstrapSettings);
        finiteValues = summary.advantage(isfinite(summary.advantage));
        values = [values; finiteValues(:)]; %#ok<AGROW>
    end

    if isempty(values)
        colorLimit = 1.5;
    else
        colorLimit = ceil(max(abs(values))*10)/10;
        colorLimit = max(colorLimit, 0.1);
    end

end

function dataRows = selectFactorRows(observations, mainRows, factorName, ...
    referenceDuration, referenceOutputSnr, referenceCoherence, ...
    referencePathwayRatio)
% selectFactorRows Hold the other displayed conditions fixed.

    if factorName == "OutputSNRdB"
        dataRows = mainRows & ...
            observations.DurationSeconds == referenceDuration & ...
            observations.TargetInputCoherence == referenceCoherence & ...
            observations.AssignedPETCO2ToMAPBandGainRatio == ...
            referencePathwayRatio;
    elseif factorName == "DurationSeconds"
        dataRows = mainRows & ...
            observations.OutputSNRdB == referenceOutputSnr & ...
            observations.TargetInputCoherence == referenceCoherence & ...
            observations.AssignedPETCO2ToMAPBandGainRatio == ...
            referencePathwayRatio;
    else
        dataRows = mainRows & ...
            observations.DurationSeconds == referenceDuration & ...
            observations.OutputSNRdB == referenceOutputSnr;
        if factorName == "TargetInputCoherence"
            dataRows = dataRows & ...
                observations.AssignedPETCO2ToMAPBandGainRatio == ...
                referencePathwayRatio;
        elseif factorName == "AssignedPETCO2ToMAPBandGainRatio"
            dataRows = dataRows & ...
                observations.TargetInputCoherence == referenceCoherence;
        end
    end

end

function dataRows = selectRowsWithFallback(observations, mainRows, factorName, ...
    referenceDuration, referenceOutputSnr, referenceCoherence, ...
    referencePathwayRatio, allowFallback)
% selectRowsWithFallback Keep custom smoke runs usable with one family.

    dataRows = selectFactorRows(observations, mainRows, factorName, ...
        referenceDuration, referenceOutputSnr, referenceCoherence, ...
        referencePathwayRatio);
    if any(dataRows)
        return
    end

    if ~allowFallback
        error("TFA:MissingProductionReferenceSlice", ...
            "The declared reference slice is absent for %s.", factorName);
    end

    % A deliberately tiny quick/design-smoke run may not contain the exact
    % declared reference family level. Retain the factor slice and the
    % reference observation settings, but do not fabricate an empty map.
    dataRows = mainRows & ...
        observations.DurationSeconds == referenceDuration & ...
        observations.OutputSNRdB == referenceOutputSnr;
    if factorName == "OutputSNRdB"
        dataRows = mainRows & observations.DurationSeconds == referenceDuration;
    elseif factorName == "DurationSeconds"
        dataRows = mainRows & observations.OutputSNRdB == referenceOutputSnr;
    end

end

function value = getReferenceFamilyValue(settings, fieldName, fallback)
% getReferenceFamilyValue Read a declared family reference or use fallback.

    value = fallback;
    if isfield(settings, "families") && ...
            isfield(settings.families, fieldName)
        value = settings.families.(fieldName);
    end

end

function map = makeMap(name, kind, variableName, label, ...
    figureHandle, sourceData, companions)
% makeMap Store one figure beside the exact cells used to draw it.

    if nargin < 7 || isempty(companions)
        companions = struct();
    end

    map = emptyMap();
    map.name = string(name);
    map.kind = string(kind);
    map.variableName = string(variableName);
    map.label = string(label);
    map.figureHandle = figureHandle;
    map.frequencyTable = sourceData.frequencyMap;
    map.metadata = sourceData.metadata;
    map.companions = companions;

end

function map = emptyMap()
% emptyMap Define one stable map record.

    map.name = "";
    map.kind = "";
    map.variableName = "";
    map.label = "";
    map.figureHandle = [];
    map.frequencyTable = table();
    map.metadata = table();
    map.companions = struct();

end

function validateSimulationResults(simulationResults)
% validateSimulationResults Check fields required by the output module.

    requiredFields = ["observations", "frequency", "settings"];
    if ~isstruct(simulationResults) || ...
            ~all(isfield(simulationResults, requiredFields))
        error("TFA:InvalidSimulationResults", ...
            "Provide results from runSimulationInterface.");
    end

    requiredObservationColumns = [ ...
        "ObservationID", "DurationSeconds", "OutputSNRdB", ...
        "TargetInputCoherence", ...
        "AssignedPETCO2ToMAPBandGainRatio"];
    observedColumns = string( ...
        simulationResults.observations.Properties.VariableNames);
    if ~all(ismember(requiredObservationColumns, observedColumns))
        error("TFA:IncompleteSimulationResults", ...
            "The observations table is missing a primary factor.");
    end

    requiredDiagnostics = [ ...
        "multipleMinusMapCoherence", ...
        "multipleMinusPartialMapCoherence"];
    if ~isfield(simulationResults.frequency, "map") || ...
            ~all(isfield(simulationResults.frequency, requiredDiagnostics))
        error("TFA:IncompleteSimulationResults", ...
            "The MAP errors or coherence diagnostics are missing.");
    end

end
