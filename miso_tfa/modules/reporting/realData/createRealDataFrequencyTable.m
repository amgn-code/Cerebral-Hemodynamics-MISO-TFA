function frequencyTable = createRealDataFrequencyTable(results)
% createRealDataFrequencyTable Create a frequency-wise real-data summary.
%
% This table compares the MISO and SISO outputs descriptively. It contains
% no truth-error or model-advantage score because real recordings do not
% provide a known generating transfer function.

    validateRealDataResults(results);

    miso = results.misoResults;
    siso = results.sisoResults;
    frequencyHz = miso.f(:);

    frequencyTable = table( ...
        frequencyHz, ...
        column(miso.map.gain), column(siso.map.gain), ...
        column(miso.co2.gain), column(siso.co2.gain), ...
        column(miso.system.multipleCoherence), ...
        column(miso.diagnostics.mapPairwiseCoherence), ...
        column(miso.diagnostics.co2PairwiseCoherence), ...
        column(miso.map.coherence.partial), ...
        column(miso.co2.coherence.partial), ...
        column(siso.map.coherence.pairwise), ...
        column(siso.co2.coherence.pairwise), ...
        column(miso.diagnostics.multipleMinusMapCoherence), ...
        column(miso.diagnostics.multipleMinusPartialMapCoherence), ...
        'VariableNames', { ...
            'FrequencyHz', ...
            'MISOMapGain', 'SISOMapGain', ...
            'MISOCO2Gain', 'SISOCO2Gain', ...
            'MISOMultipleCoherence', ...
            'MISOMapPairwiseCoherence', ...
            'MISOCO2PairwiseCoherence', ...
            'MISOMapPartialCoherence', ...
            'MISOCO2PartialCoherence', ...
            'SISOMapCoherence', 'SISOCO2Coherence', ...
            'MISOMinusMapCoherence', ...
            'MISOMinusPartialMapCoherence'});

end

function values = column(values)
% column Make the table constructor independent of row-vector orientation.

    values = values(:);

end

function validateRealDataResults(results)
% validateRealDataResults Check the combined interface result shape.

    if ~isstruct(results) || ...
            ~isfield(results, "misoResults") || ...
            ~isfield(results, "sisoResults") || ...
            isempty(results.misoResults) || isempty(results.sisoResults)
        error( ...
            "TFA:InvalidRealDataResults", ...
            "Provide combined results from runMisoSisoRealData.");
    end

    if numel(results.misoResults.f) ~= numel(results.sisoResults.f) || ...
            any(results.misoResults.f(:) ~= results.sisoResults.f(:))
        error( ...
            "TFA:FrequencyGridMismatch", ...
            "MISO and SISO results must use the same frequency grid.");
    end

end
