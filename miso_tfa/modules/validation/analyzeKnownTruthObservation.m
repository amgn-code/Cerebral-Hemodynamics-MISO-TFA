function analysis = analyzeKnownTruthObservation( ...
    training, validation, settings)
% analyzeKnownTruthObservation Fit SISO and MISO to one paired observation.

    trainingSpectra = estimateWelchSpectra( ...
        training.map, training.co2, training.cbv, training.fs, ...
        settings.welch);
    validationSpectra = estimateWelchSpectra( ...
        validation.map, validation.co2, validation.cbv, validation.fs, ...
        settings.welch);

    frequencyHz = trainingSpectra.f;
    frequencyMask = ...
        frequencyHz >= settings.frequencyRangeHz(1) & ...
        frequencyHz <= settings.frequencyRangeHz(2);

    trueMap = freqz( ...
        training.truth.mapImpulseResponse, 1, ...
        frequencyHz, training.fs);
    trueCo2 = freqz( ...
        training.truth.co2ImpulseResponse, 1, ...
        frequencyHz, training.fs);

    siso = runSISOTFA(trainingSpectra, settings.phase);
    miso = runMISOTFA(trainingSpectra, settings.phase);

    analysis.frequencyHz = frequencyHz(frequencyMask);
    analysis.truth.map = trueMap(frequencyMask);
    analysis.truth.co2 = trueCo2(frequencyMask);
    analysis.estimate.map.siso = ...
        siso.map.transferFunction(frequencyMask);
    analysis.estimate.map.miso = ...
        miso.map.transferFunction(frequencyMask);
    analysis.estimate.co2.siso = ...
        siso.co2.transferFunction(frequencyMask);
    analysis.estimate.co2.miso = ...
        miso.co2.transferFunction(frequencyMask);

    errorFloor = settings.metrics.errorFloor;
    phaseMinimumGainFraction = ...
        settings.metrics.phaseMinimumTruthGainFraction;
    analysis.frequencyError.map.siso = ...
        calculateFrequencyTruthErrors( ...
            analysis.estimate.map.siso, analysis.truth.map, errorFloor, ...
            phaseMinimumGainFraction);
    analysis.frequencyError.map.miso = ...
        calculateFrequencyTruthErrors( ...
            analysis.estimate.map.miso, analysis.truth.map, errorFloor, ...
            phaseMinimumGainFraction);
    analysis.frequencyError.co2.siso = ...
        calculateFrequencyTruthErrors( ...
            analysis.estimate.co2.siso, analysis.truth.co2, errorFloor, ...
            phaseMinimumGainFraction);
    analysis.frequencyError.co2.miso = ...
        calculateFrequencyTruthErrors( ...
            analysis.estimate.co2.miso, analysis.truth.co2, errorFloor, ...
            phaseMinimumGainFraction);

    analysis.frequencyAdvantage.map = calculatePathwayAdvantages( ...
        analysis.frequencyError.map, errorFloor);
    analysis.frequencyAdvantage.co2 = calculatePathwayAdvantages( ...
        analysis.frequencyError.co2, errorFloor);

    analysis.summary.map.siso = calculateKnownTruthMetrics( ...
        frequencyHz, siso.map.transferFunction, trueMap, ...
        settings.frequencyRangeHz, ...
        settings.metrics.extremeCoefficientThreshold, ...
        phaseMinimumGainFraction);
    analysis.summary.map.miso = calculateKnownTruthMetrics( ...
        frequencyHz, miso.map.transferFunction, trueMap, ...
        settings.frequencyRangeHz, ...
        settings.metrics.extremeCoefficientThreshold, ...
        phaseMinimumGainFraction);
    analysis.summary.co2.siso = calculateKnownTruthMetrics( ...
        frequencyHz, siso.co2.transferFunction, trueCo2, ...
        settings.frequencyRangeHz, ...
        settings.metrics.extremeCoefficientThreshold, ...
        phaseMinimumGainFraction);
    analysis.summary.co2.miso = calculateKnownTruthMetrics( ...
        frequencyHz, miso.co2.transferFunction, trueCo2, ...
        settings.frequencyRangeHz, ...
        settings.metrics.extremeCoefficientThreshold, ...
        phaseMinimumGainFraction);

    analysis.summaryAdvantage.map = calculateSummaryAdvantages( ...
        analysis.summary.map.siso, analysis.summary.map.miso, ...
        errorFloor);
    analysis.summaryAdvantage.co2 = calculateSummaryAdvantages( ...
        analysis.summary.co2.siso, analysis.summary.co2.miso, ...
        errorFloor);

    analysis.prediction.sisoMap = ...
        calculateValidationPredictionError( ...
            validationSpectra, siso.map.transferFunction, ...
            zeros(size(siso.co2.transferFunction)), ...
            settings.frequencyRangeHz);
    analysis.prediction.sisoCo2 = ...
        calculateValidationPredictionError( ...
            validationSpectra, ...
            zeros(size(siso.map.transferFunction)), ...
            siso.co2.transferFunction, settings.frequencyRangeHz);
    analysis.prediction.miso = ...
        calculateValidationPredictionError( ...
            validationSpectra, ...
            miso.map.transferFunction, ...
            miso.co2.transferFunction, ...
            settings.frequencyRangeHz);
    analysis.prediction.advantage = calculateErrorAdvantage( ...
        analysis.prediction.sisoMap, ...
        analysis.prediction.miso, errorFloor);

    mapPower = real(trainingSpectra.map.power(frequencyMask));
    co2Power = real(trainingSpectra.co2.power(frequencyMask));
    inputCoherence = abs( ...
        trainingSpectra.cross.mapCo2(frequencyMask)).^2 ./ ...
        max(mapPower.*co2Power, errorFloor);
    inputCoherence = min(1, max(0, real(inputCoherence)));

    analysis.diagnostics.inputCoherence = inputCoherence;
    analysis.diagnostics.multipleCoherence = ...
        miso.system.multipleCoherence(frequencyMask);
    analysis.diagnostics.realizedPSDShapeOverlap = ...
        calculatePSDShapeOverlap(mapPower, co2Power);
    analysis.diagnostics.realizedPETCO2ToMAPFluctuationSDRatio = ...
        std(training.co2, "omitnan")/std(training.map, "omitnan");
    analysis.diagnostics.realizedPETCO2ContributionPowerShare = ...
        calculatePetco2ContributionPowerShare( ...
            training.mapContribution, training.co2Contribution);
    analysis.diagnostics.achievedPETCO2ToMAPBandGainRatio = ...
        training.truth.achievedPETCO2ToMAPBandGainRatio;
    analysis.diagnostics.rawConditionNumber = ...
        miso.diagnostics.conditionNumber(frequencyMask);
    analysis.diagnostics.normalizedConditionNumber = ...
        miso.diagnostics.normalizedConditionNumber(frequencyMask);
    analysis.diagnostics.normalizedDeterminant = ...
        miso.diagnostics.normalizedDeterminant(frequencyMask);
    analysis.diagnostics.mapPairwiseCoherence = ...
        miso.diagnostics.mapPairwiseCoherence(frequencyMask);
    analysis.diagnostics.co2PairwiseCoherence = ...
        miso.diagnostics.co2PairwiseCoherence(frequencyMask);
    analysis.diagnostics.multipleMinusMapCoherence = ...
        miso.diagnostics.multipleMinusMapCoherence(frequencyMask);
    analysis.diagnostics.multipleMinusPartialMapCoherence = ...
        miso.diagnostics.multipleMinusPartialMapCoherence(frequencyMask);
    analysis.diagnostics.numWelchWindows = ...
        trainingSpectra.welchInfo.numWindows;
    analysis.diagnostics.numAnalyzedSamples = numel(training.map);
    analysis.diagnostics.analyzedDurationSeconds = ...
        numel(training.map)/training.fs;

end

function advantages = calculatePathwayAdvantages(errors, errorFloor)
% calculatePathwayAdvantages Compare frequency-wise SISO and MISO errors.

    advantages.gain = calculateErrorAdvantage( ...
        errors.siso.gain, errors.miso.gain, errorFloor);
    advantages.phase = calculateErrorAdvantage( ...
        errors.siso.phase, errors.miso.phase, errorFloor);
    advantages.complex = calculateErrorAdvantage( ...
        errors.siso.complex, errors.miso.complex, errorFloor);

end

function advantages = calculateSummaryAdvantages( ...
    siso, miso, errorFloor)
% calculateSummaryAdvantages Compare whole-range pathway errors.

    advantages.gain = calculateErrorAdvantage( ...
        siso.meanAbsoluteGainError, ...
        miso.meanAbsoluteGainError, errorFloor);
    advantages.phase = calculateErrorAdvantage( ...
        siso.meanAbsolutePhaseErrorRadians, ...
        miso.meanAbsolutePhaseErrorRadians, errorFloor);
    advantages.complex = calculateErrorAdvantage( ...
        siso.normalizedComplexError, ...
        miso.normalizedComplexError, errorFloor);

end
