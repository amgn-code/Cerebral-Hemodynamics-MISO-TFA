function validateTfaSettings(settings)
% validateTfaSettings Check the input contract and scientifically valid limits.

    arguments
        settings (1,1) struct
    end
    assert(any(settings.mode == ["data", "simulation"]), ...
        "TFA:Mode", 'Set mode to "data" or "simulation".');
    analysis = settings.analysis;
    validateattributes(analysis.fsTarget, "numeric", {"scalar", "positive", "finite"});
    validateattributes(analysis.frequencyRangeHz, "numeric", ...
        {"vector", "numel", 2, "nonnegative", "increasing", "finite"});
    assert(analysis.frequencyRangeHz(2) <= analysis.fsTarget/2, ...
        "TFA:FrequencyRange", "The reporting band must be below Nyquist.");
    welch = analysis.pwelch;
    validateattributes(welch.windowLengthSeconds, "numeric", {"scalar", "positive", "finite"});
    validateattributes(welch.windowOverlap, "numeric", ...
        {"scalar", ">=", 0, "<", 1, "finite"});
    validateattributes(welch.minimumWindows, "numeric", {"scalar", "integer", "positive"});
    assert(round(welch.windowLengthSeconds*analysis.fsTarget) >= 4, ...
        "TFA:WelchWindow", "Use at least four samples per Welch window.");
    windowSamples = round(welch.windowLengthSeconds*analysis.fsTarget);
    assert(round(welch.windowOverlap*windowSamples) < windowSamples, ...
        "TFA:WelchOverlap", "Welch overlap must leave a positive sample step.");
    frequencyHz = (0:floor(windowSamples/2))*analysis.fsTarget/windowSamples;
    assert(nnz(frequencyHz >= analysis.frequencyRangeHz(1) & ...
        frequencyHz <= analysis.frequencyRangeHz(2)) >= 2, "TFA:FrequencyBins", ...
        "The reporting band needs at least two frequency bins.");
    kernel = welch.smoothingKernel;
    assert(isvector(kernel) && mod(numel(kernel), 2) == 1 && ...
        all(isfinite(kernel) & kernel >= 0) && abs(sum(kernel) - 1) < 1e-12, ...
        "TFA:SmoothingKernel", "Use an odd, nonnegative smoothing kernel summing to one.");
    assert(any(settings.plots.phaseStyle == ["wrapped", "unwrapped"]), ...
        "TFA:PhaseStyle", 'Use "wrapped" or "unwrapped" phase.');
    if settings.mode == "data"
        assert(~isempty(settings.data.paths), "TFA:DataPaths", ...
            "Set data.paths to recording files or folders in runAnalysis.m.");
        return
    end

    simulation = settings.simulation;
    assert(any(simulation.design == ["oneAtATime", "factorial"]), ...
        "TFA:Design", 'Use "oneAtATime" or "factorial".');
    validateattributes(simulation.repetitions, "numeric", {"scalar", "integer", "positive"});
    validateattributes(simulation.randomSeed, "numeric", ...
        {"scalar", "integer", "nonnegative", "finite"});
    validateattributes(simulation.masterDurationSeconds, "numeric", {"scalar", "positive", "finite"});
    validateattributes(simulation.inputs.mapStandardDeviation, "numeric", ...
        {"scalar", "positive", "finite"});
    validateattributes(simulation.cbvNormalizationReference, "numeric", ...
        {"scalar", "positive", "finite"});
    validateattributes(simulation.bootstrapSamples, "numeric", ...
        {"scalar", "integer", "nonnegative", "finite"});
    validateattributes(simulation.confidenceLevel, "numeric", {"scalar", ">", 0, "<", 1});
    assert(all(ismember(simulation.metrics, ["gain", "phase", "complex"])), ...
        "TFA:Metrics", 'Accuracy metrics are "gain", "phase", and optionally "complex".');
    assert(any(simulation.noiseSpectrum == ["white", "signalShaped"]), ...
        "TFA:NoiseSpectrum", 'Use "white" or "signalShaped" noise.');
    assert(numel(unique(simulation.vary)) == numel(simulation.vary), ...
        "TFA:DuplicateFactors", "Each varied condition must appear once.");
    for factor = string(simulation.vary(:)).'
        assert(isfield(simulation.baseline, factor) && isfield(simulation.ranges, factor), ...
            "TFA:UnknownCondition", "Declare a baseline and range for %s.", factor);
    end
    conditions = createSimulationConditions(simulation);
    assert(all(conditions.inputCoherence >= 0 & conditions.inputCoherence <= 1), ...
        "TFA:InputCoherence", "Input coherence must be between zero and one.");
    assert(all(conditions.co2FluctuationRatio >= 0 & isfinite(conditions.co2FluctuationRatio)), ...
        "TFA:FluctuationRatio", "Use nonnegative finite input fluctuation ratios.");
    assert(all(conditions.co2GainRatio >= 0 & isfinite(conditions.co2GainRatio)), ...
        "TFA:GainRatio", "Use nonnegative finite pathway gain ratios.");
    assert(all(conditions.mapTimeConstantSeconds > 0 & conditions.co2TimeConstantSeconds > 0), ...
        "TFA:TimeConstants", "Pathway time constants must be positive.");
    assert(all(conditions.co2DelaySeconds >= 0), ...
        "TFA:PathwayDelay", "The causal CO2 pathway delay must be nonnegative.");
    timeNames = ["mapTimeConstantSeconds", "co2TimeConstantSeconds", ...
        "co2DelaySeconds", "inputLagSeconds", "durationSeconds", "alignmentErrorSeconds"];
    assert(all(isfinite(conditions{:, timeNames}), "all"), ...
        "TFA:FiniteTimes", "All timing values must be finite.");
    noiseLevels = conditions{:, ["outputSnrDb", "mapInputSnrDb", "co2InputSnrDb"]};
    assert(all(isfinite(noiseLevels) | noiseLevels == Inf, "all"), ...
        "TFA:SNR", "Noise levels must be finite dB values or positive Inf for noise-free input.");
    longestKernelSeconds = max([conditions.mapTimeConstantSeconds; ...
        conditions.co2TimeConstantSeconds])*simulation.pathways.filterDurationTimeConstants ...
        + max(conditions.co2DelaySeconds);
    assert(simulation.pathways.burnInSeconds >= longestKernelSeconds, ...
        "TFA:BurnIn", "Increase burnInSeconds to cover the longest generating kernel.");
    calibrationBand = simulation.pathways.calibrationBandHz;
    assert(numel(calibrationBand) == 2 && calibrationBand(1) >= 0 && ...
        calibrationBand(2) > calibrationBand(1) && calibrationBand(2) <= analysis.fsTarget/2, ...
        "TFA:CalibrationBand", "Pathway calibrationBandHz must lie within zero to Nyquist.");
    assert(all(conditions.durationSeconds <= simulation.masterDurationSeconds), ...
        "TFA:MasterDuration", "masterDurationSeconds must cover the longest tested recording.");
    windowSamples = round(welch.windowLengthSeconds*analysis.fsTarget);
    overlapSamples = round(welch.windowOverlap*windowSamples);
    totalShift = conditions.alignmentErrorSeconds ...
        + analysis.preprocessing.co2DelayCorrectionSeconds;
    shortestSamples = round(conditions.durationSeconds*analysis.fsTarget) ...
        - abs(round(totalShift*analysis.fsTarget));
    windows = floor((shortestSamples - windowSamples)/(windowSamples - overlapSamples)) + 1;
    assert(all(windows >= welch.minimumWindows), "TFA:ShortRecording", ...
        "A condition leaves too few Welch windows after alignment. Increase duration or reduce the window.");
    if simulation.inputs.spectrumModel == "ncMonotonic"
        assert(all(conditions.spectralSimilarity == simulation.baseline.spectralSimilarity), ...
            "TFA:SpectralSimilarity", ...
            'A spectralSimilarity sweep requires the existing "gaussian" spectrum option.');
    end
end
