classdef finalSimulationStudyTest < matlab.unittest.TestCase
    % finalSimulationStudyTest Verify the final experiment boundaries.

    properties
        Study
    end

    methods (TestClassSetup)
        function createSmallFinalStudy(testCase)
            projectRoot = fileparts(fileparts(mfilename("fullpath")));
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture( ...
                    projectRoot, IncludingSubfolders=true));
            output = defaultSimulationOutputSettings("off");
            output.createFigures = false;
            output.bootstrap.numSamples = 20;
            testCase.Study = runFinalSimulationStudy(1, output);
        end
    end

    methods (Test)
        function namedExperimentsContainOnlyDeclaredRows(testCase)
            study = testCase.Study;

            testCase.verifyEqual( ...
                unique(study.experiments.core.results.observations.Experiment), ...
                "Main");
            testCase.verifyEqual( ...
                string({study.experiments.phase.maps.selectedExperiments}), ...
                ["Main" "Main" "Main"]);
            testCase.verifyEqual( ...
                study.experiments.inputNoise.maps(1).selectedExperiments, ...
                "MAP input noise");
            testCase.verifyEqual( ...
                study.experiments.inputNoise.maps(2).selectedExperiments, ...
                "CO2 input noise");
            testCase.verifyEqual( ...
                study.experiments.alignment.maps.selectedExperiments, ...
                "Alignment");
            testCase.verifyEqual( ...
                study.experiments.whiteNoise.maps.selectedExperiments, ...
                "White output noise");
        end

        function phaseExperimentCrossesOnlyDeclaredLevels(testCase)
            design = testCase.Study.experiments.phase.results.familyDesign;

            testCase.verifyEqual( ...
                unique(design.TargetInputCoherence)', [0.15 0.50 0.95]);
            testCase.verifyEqual( ...
                unique(design.InputPhaseLagSeconds)', [-6 0 4]);
            testCase.verifyEqual(height(design), 9);
            testCase.verifyTrue(all( ...
                design.PETCO2ToMAPBandGainRatio == 1));
        end

        function productionMapsRejectMissingReferenceSlice(testCase)
            simulation = testCase.Study.experiments.core.results;
            simulation.settings.families.referenceTargetInputCoherence = 0.33;
            output = defaultSimulationOutputSettings("off");
            output.createFigures = false;

            testCase.verifyError( ...
                @() createSimulationOutputs(simulation, output), ...
                "TFA:MissingProductionReferenceSlice");
        end

        function analyticCompanionUsesOnePairedMask(testCase)
            companion = testCase.Study.experiments.core.outputs. ...
                primaryMaps(1).companions.analyticReference;

            testCase.verifyTrue(all( ...
                companion.PairedValidN == companion.ValidN));
            testCase.verifyTrue(ismember( ...
                "EmpiricalMISOErrorMean", ...
                string(companion.Properties.VariableNames)));
            testCase.verifyFalse(ismember( ...
                "AnalyticBiasReferenceAdvantage", ...
                string(companion.Properties.VariableNames)));
        end

        function finalExportCarriesMapMetadataAndManifest(testCase)
            import matlab.unittest.fixtures.TemporaryFolderFixture
            temporary = testCase.applyFixture(TemporaryFolderFixture);
            outputFolder = fullfile(temporary.Folder, "final_export");

            exported = exportFinalSimulationStudy( ...
                testCase.Study, outputFolder);

            testCase.verifyEqual(height(exported.mapIndex), 17);
            testCase.verifyEqual( ...
                numel(unique(exported.mapIndex.MapName)), 17);
            testCase.verifyTrue(isfile(exported.manifestFile));
            testCase.verifyTrue(isfile(fullfile( ...
                exported.sourceFolder, ...
                "input_coherence_metadata.csv")));
            source = readtable(fullfile( ...
                exported.sourceFolder, ...
                "input_coherence_frequency_map.csv"));
            testCase.verifyTrue(ismember( ...
                "PairedValidN", string(source.Properties.VariableNames)));
            expected = testCase.Study.experiments.core.outputs. ...
                primaryMaps(1).frequencyTable;
            testCase.verifyEqual( ...
                source.Advantage, expected.Advantage, AbsTol=1e-12);
            testCase.verifyEqual( ...
                source.PairedValidN, expected.PairedValidN);
        end
    end
end
