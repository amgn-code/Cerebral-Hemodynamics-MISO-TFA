function reportFile = writeApproachPaperSimulationAudit( ...
    audit, outputFolder)
% writeApproachPaperSimulationAudit Write a readable run-audit report.

    auditFolder = fullfile(outputFolder, "Simulation_Audit");
    if ~exist(auditFolder, "dir")
        mkdir(auditFolder);
    end
    reportFile = fullfile(auditFolder, "simulation_audit.md");
    fileId = fopen(reportFile, "w");
    if fileId < 0
        error( ...
            "TFA:CannotWriteSimulationAudit", ...
            "Could not create simulation audit report: %s", ...
            reportFile);
    end
    closeFile = onCleanup(@() fclose(fileId));

    fprintf(fileId, "# Known-truth simulation audit\n\n");
    fprintf(fileId, "Profile: `%s`  \n", audit.profileName);
    fprintf(fileId, "Evidence level: %s  \n", audit.evidenceLevel);
    fprintf(fileId, "Elapsed numerical time: %s\n\n", ...
        formatElapsedTime(audit.elapsedSeconds));
    fprintf(fileId, ...
        ['This report checks design execution, numerical support, and ' ...
         'checkpoint stability before any result narrative is written. ' ...
         'Sparse realized-value cells are reported descriptively and are ' ...
         'not automatically treated as design failures.\n\n']);

    fprintf(fileId, "## Core execution checks\n\n");
    writeOverviewTable(fileId, audit.overview);

    fprintf(fileId, "\n## Assigned-factor balance\n\n");
    fprintf(fileId, ...
        ['All %d marginal level checks passed: **%s**. All %d ' ...
         'pairwise cell checks passed: **%s**.\n\n'], ...
        height(audit.marginalBalance), ...
        yesNo(all(audit.marginalBalance.Pass)), ...
        height(audit.pairwiseBalance), ...
        yesNo(isempty(audit.pairwiseBalance) || ...
            all(audit.pairwiseBalance.Pass)));

    fprintf(fileId, "## Realized-bin occupancy\n\n");
    writeOccupancySummary(fileId, audit.realizedBinOccupancy);
    fprintf(fileId, ...
        ['Across the joint realized-characteristic grids, %d of %d cells ' ...
         'meet the prespecified display minimum and %d cells are empty. ' ...
         'These values measure support; fixed boundaries were not moved ' ...
         'to improve occupancy.\n\n'], ...
        nnz(audit.realizedPairOccupancy.MeetsDisplayMinimum), ...
        height(audit.realizedPairOccupancy), ...
        nnz(audit.realizedPairOccupancy.FamilyN == 0));

    fprintf(fileId, "## Validity audit\n\n");
    fprintf(fileId, ...
        ['The retained observation table contains %d metric-condition ' ...
         'support checks. %d meet the minimum valid-family rule; %d do ' ...
         'not. A total of %d invalid metric values were retained as ' ...
         'missing rather than silently discarded.\n\n'], ...
        height(audit.validity), ...
        nnz(audit.validity.MeetsMinimumN), ...
        nnz(~audit.validity.MeetsMinimumN), ...
        sum(audit.validity.InvalidN));

    fprintf(fileId, "## Balanced-checkpoint stability\n\n");
    fprintf(fileId, ...
        ['The following descriptive means compare complete balanced ' ...
         'blocks. Change from final is the checkpoint mean minus the ' ...
         'full-run mean; it is not a separate hypothesis test.\n\n']);
    writeStabilityTable(fileId, audit.stability);

    fprintf(fileId, "\n## Machine-readable audit tables\n\n");
    fprintf(fileId, ...
        ['The corresponding detailed tables are exported to the `Tables` ' ...
         'folder and the approach-paper workbook: overview, marginal ' ...
         'balance, pairwise balance, one-dimensional realized occupancy, ' ...
         'joint realized occupancy, observation validity, and checkpoint ' ...
         'stability.\n']);

    clear closeFile
    reportFile = string(reportFile);

end

function writeOverviewTable(fileId, overview)
% writeOverviewTable Write the concise pass/fail table.

    fprintf(fileId, ...
        "| Check | Observed | Expected | Pass |\n");
    fprintf(fileId, ...
        "|---|---:|---:|:---:|\n");
    for rowIndex = 1:height(overview)
        fprintf(fileId, "| %s | %s | %s | %s |\n", ...
            escapeMarkdown(overview.Check(rowIndex)), ...
            escapeMarkdown(overview.Observed(rowIndex)), ...
            escapeMarkdown(overview.Expected(rowIndex)), ...
            yesNo(overview.Pass(rowIndex)));
    end

end

function writeOccupancySummary(fileId, occupancy)
% writeOccupancySummary Summarize every realized one-factor grid.

    characteristics = unique(occupancy.Characteristic, "stable");
    fprintf(fileId, ...
        "| Characteristic | Minimum cell N | Maximum cell N | " + ...
        "Cells meeting display minimum | Empty cells |\n");
    fprintf(fileId, "|---|---:|---:|---:|---:|\n");
    for index = 1:numel(characteristics)
        rows = occupancy.Characteristic == characteristics(index);
        fprintf(fileId, "| %s | %d | %d | %d of %d | %d |\n", ...
            escapeMarkdown(characteristics(index)), ...
            min(occupancy.FamilyN(rows)), ...
            max(occupancy.FamilyN(rows)), ...
            nnz(occupancy.MeetsDisplayMinimum(rows)), nnz(rows), ...
            nnz(occupancy.FamilyN(rows) == 0));
    end

end

function writeStabilityTable(fileId, stability)
% writeStabilityTable Write checkpoint mean and change from final.

    fprintf(fileId, ...
        "| Families | Blocks | Metric | Mean | SD | Valid N | " + ...
        "Change from final |\n");
    fprintf(fileId, "|---:|---:|---|---:|---:|---:|---:|\n");
    for rowIndex = 1:height(stability)
        fprintf(fileId, ...
            "| %d | %g | %s | %.5g | %.5g | %d | %.5g |\n", ...
            stability.FamiliesUsed(rowIndex), ...
            stability.CheckpointBlocks(rowIndex), ...
            escapeMarkdown(stability.Metric(rowIndex)), ...
            stability.Mean(rowIndex), stability.SD(rowIndex), ...
            stability.ValidN(rowIndex), ...
            stability.ChangeFromFinal(rowIndex));
    end

end

function text = formatElapsedTime(seconds)
% formatElapsedTime Produce a readable duration without hiding seconds.

    if ~isfinite(seconds)
        text = "not recorded";
    elseif seconds < 60
        text = compose("%.1f seconds", seconds);
    elseif seconds < 3600
        text = compose("%.1f minutes (%.1f seconds)", ...
            seconds/60, seconds);
    else
        text = compose("%.2f hours (%.1f seconds)", ...
            seconds/3600, seconds);
    end

end

function answer = yesNo(value)
% yesNo Format logical audit status.

    if value
        answer = "yes";
    else
        answer = "no";
    end

end

function escaped = escapeMarkdown(value)
% escapeMarkdown Keep generated table cells structurally valid.

    escaped = replace(string(value), "|", "\|");

end
